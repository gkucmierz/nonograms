const supportedLocales = Object.keys(messages).filter(
  (code) => requiredKeys.every((k) => messages[code] && messages[code][k])
);

const detectLocale = () => {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem('locale');
    if (saved && supportedLocales.includes(saved)) {
      return saved;
    }
  }
  if (typeof navigator === 'undefined') return 'en';
  const browserLocale = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
  let short = browserLocale.toLowerCase().split('-')[0];

  // Handle aliases for legacy/variant codes
  const aliases = {
    'in': 'id', // Indonesian legacy
    'iw': 'he', // Hebrew legacy
    'fil': 'tl' // Filipino -> Tagalog
  };

  if (aliases[short]) {
    short = aliases[short];
  }

  return supportedLocales.includes(short) ? short : 'en';
};

const locale = ref(detectLocale());

const format = (text, params = {}) => {
  return text.replace(/\{(\w+)\}/g, (_, key) => {
    const value = params[key];
    return value === undefined ? `{${key}}` : String(value);
  });
};

const t = (key, params) => {
  const lang = messages[locale.value] || messages.en;
  const value = lang[key] || messages.en[key] || key;
  return typeof value === 'string' ? format(value, params) : key;
};

const setLocale = (value) => {
  locale.value = supportedLocales.includes(value) ? value : 'en';
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('locale', locale.value);
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale.value;
    document.title = t('app.title');
  }
};

if (typeof document !== 'undefined') {
  document.documentElement.lang = locale.value;
  document.title = messages[locale.value]?.['app.title'] || 'Nonograms';
}

export function useI18n() {
  return {
    locale: computed(() => locale.value),
    t,
    setLocale,
    locales: computed(() => supportedLocales)
  };
}
